# LOAD SECURITY MASTER
# ============================================================

def load_security_master() -> pd.DataFrame:

    dataframe = pd.read_csv(
        SECURITY_MASTER_FILE,
        low_memory=False,
    )

    dataframe.columns = [
        normalize_column_name(
            column
        )
        for column in dataframe.columns
    ]

    required_columns = {
        "security_id",
        "symbol",
    }

    missing = (
        required_columns
        - set(
            dataframe.columns
        )
    )

    if missing:

        raise RuntimeError(
            "Security Master missing required columns: "
            + ", ".join(
                sorted(
                    missing
                )
            )
        )

    dataframe[
        "security_id"
    ] = (
        dataframe[
            "security_id"
        ]
        .fillna("")
        .astype(str)
        .str.strip()
    )

    dataframe[
        "symbol"
    ] = (
        dataframe[
            "symbol"
        ]
        .map(
            normalize_symbol
        )
    )

    return dataframe


# ============================================================
# LOAD CURRENT F&O UNIVERSE
# ============================================================

def load_current_fno_universe() -> pd.DataFrame:

    dataframe = pd.read_csv(
        CURRENT_FNO_UNIVERSE_FILE,
        low_memory=False,
    )

    dataframe.columns = [
        normalize_column_name(
            column
        )
        for column in dataframe.columns
    ]

    if "symbol" not in dataframe.columns:

        raise RuntimeError(
            "Current F&O universe has no symbol column."
        )

    dataframe[
        "symbol"
    ] = (
        dataframe[
            "symbol"
        ]
        .map(
            normalize_symbol
        )
    )

    dataframe = dataframe[
        dataframe[
            "symbol"
        ].ne("")
    ].copy()

    dataframe = (
        dataframe
        .drop_duplicates(
            subset=[
                "symbol",
            ],
            keep="first",
        )
        .reset_index(
            drop=True
        )
    )

    return dataframe


