# ============================================================
# VALIDATE FNO-001
# ============================================================

def validate_fno001_summary(
    summary: dict[str, object],
) -> None:

    status = str(
        summary.get(
            "status",
            "",
        )
    ).strip().upper()

    if status != "SUCCESS":

        raise RuntimeError(
            "FNO-001 status is not SUCCESS."
        )

    reconciliation_ok = bool(
        summary.get(
            "reconciliation_ok",
            False,
        )
    )

    if not reconciliation_ok:

        raise RuntimeError(
            "FNO-001 reconciliation did not pass."
        )

    critical_issues = int(
        summary.get(
            "critical_issues",
            0,
        )
    )

    if critical_issues != 0:

        raise RuntimeError(
            "FNO-001 contains critical issues."
        )


# ============================================================
# MASTER STRUCTURAL VALIDATION
# ============================================================

def validate_security_master(
    dataframe: pd.DataFrame,
) -> dict[str, int]:

    duplicate_security_ids = int(
        dataframe.duplicated(
            subset=[
                "security_id",
            ],
            keep=False,
        ).sum()
    )

    duplicate_symbols = int(
        dataframe.duplicated(
            subset=[
                "symbol",
            ],
            keep=False,
        ).sum()
    )

    blank_security_ids = int(
        dataframe[
            "security_id"
        ]
        .fillna("")
        .astype(str)
        .str.strip()
        .eq("")
        .sum()
    )

    blank_symbols = int(
        dataframe[
            "symbol"
        ]
        .fillna("")
        .astype(str)
        .str.strip()
        .eq("")
        .sum()
    )

    critical_issues = (
        duplicate_security_ids
        + duplicate_symbols
        + blank_security_ids
        + blank_symbols
    )

    return {
        "duplicate_security_ids":
            duplicate_security_ids,

        "duplicate_symbols":
            duplicate_symbols,

        "blank_security_ids":
            blank_security_ids,

        "blank_symbols":
            blank_symbols,

        "critical_issues":
            critical_issues,
    }


# ============================================================
# DETECT NEW CURRENT SYMBOLS
# ============================================================

def detect_pending_inclusions(
    security_master: pd.DataFrame,
    current_universe: pd.DataFrame,
) -> pd.DataFrame:

    master_symbols = set(
        security_master[
            "symbol"
        ]
    )

    current_symbols = set(
        current_universe[
            "symbol"
        ]
    )

    pending_symbols = (
        current_symbols
        - master_symbols
    )

    pending = current_universe[
        current_universe[
            "symbol"
        ].isin(
            pending_symbols
        )
    ].copy()

    if not pending.empty:

        pending[
            "onboarding_status"
        ] = "PENDING_SECURITY_MASTER_ONBOARDING"

        pending[
            "security_id_status"
        ] = "NOT_ASSIGNED"

        pending[
            "automatic_promotion"
        ] = False

    return pending


# ============================================================
# BUILD CANDIDATE SECURITY MASTER
# ============================================================

def build_candidate_master(
    security_master: pd.DataFrame,
    current_universe: pd.DataFrame,
    *,
    as_of_date: str,
) -> pd.DataFrame:

    candidate = security_master.copy()

    current_symbols = set(
        current_universe[
            "symbol"
        ]
    )

    # --------------------------------------------------------
    # Preserve prior membership before changing anything
    # --------------------------------------------------------

    if "is_fno" in candidate.columns:

        previous_fno = (
            candidate[
                "is_fno"
            ]
            .map(
                parse_bool
            )
        )

    elif "fno_flag" in candidate.columns:

        previous_fno = (
            candidate[
                "fno_flag"
            ]
            .map(
                parse_bool
            )
        )

    else:

        previous_fno = pd.Series(
            False,
            index=candidate.index,
        )

    candidate[
        "previous_fno_member"
    ] = previous_fno

    # --------------------------------------------------------
    # Authoritative current membership
    # --------------------------------------------------------

    candidate[
        "current_fno_member"
    ] = (
        candidate[
            "symbol"
        ]
        .isin(
            current_symbols
        )
    )

    # --------------------------------------------------------
    # Existing AQSD compatibility fields
    # --------------------------------------------------------

    candidate[
        "is_fno"
    ] = (
        candidate[
            "current_fno_member"
        ]
    )

    candidate[
        "fno_flag"
    ] = candidate[
        "current_fno_member"
    ].map(
        {
            True: "YES",
            False: "NO",
        }
    )

    # --------------------------------------------------------
    # Membership classification
    # --------------------------------------------------------

    def membership_change(
        row: pd.Series,
    ) -> str:

        previous = bool(
            row[
                "previous_fno_member"
            ]
        )

        current = bool(
            row[
                "current_fno_member"
            ]
        )

        if previous and current:
            return "UNCHANGED_CURRENT"

        if previous and not current:
            return "EXCLUDED_FROM_CURRENT_FNO"

        if not previous and current:
            return "NEW_CURRENT_FNO"

        return "NON_FNO"

    candidate[
        "fno_membership_change"
    ] = candidate.apply(
        membership_change,
        axis=1,
    )

    candidate[
        "fno_membership_status"
    ] = candidate[
        "current_fno_member"
    ].map(
        {
            True: "CURRENT_FNO",
            False: "NOT_CURRENT_FNO",
        }
    )

    candidate[
        "fno_membership_asof"
    ] = as_of_date

    candidate[
        "fno_membership_source"
    ] = "NSE_FO_MII_CONTRACT_MASTER"

    candidate[
        "fno_membership_module"
    ] = MODULE_ID

    candidate[
        "fno_membership_version"
    ] = MODULE_VERSION

    candidate[
        "fno_membership_updated_at"
    ] = (
        datetime.now()
        .astimezone()
        .isoformat(
            timespec="seconds"
        )
    )

    # --------------------------------------------------------
    # IMPORTANT:
    # active_flag is NOT modified.
    #
    # A stock can remain an active NSE security even when
    # removed from the F&O segment.
    # --------------------------------------------------------

    return candidate


