def determine_rotation_state(
    *,
    current_rank: int,
    previous_rank: int | None,
    weekly_rank: int | None,
    current_score: int,
    daily_score_change: int | None,
    weekly_score_change: int | None,
    total_sectors: int,
) -> str:
    """
    Classify the current rotation state.
    """

    current_leader = is_current_leader(
        current_rank
    )

    previous_leader = (
        is_current_leader(previous_rank)
        if previous_rank is not None
        else False
    )

    current_laggard = is_laggard(
        rank=current_rank,
        total_sectors=total_sectors,
    )

    previous_laggard = (
        is_laggard(
            rank=previous_rank,
            total_sectors=total_sectors,
        )
        if previous_rank is not None
        else False
    )

    if (
        current_leader
        and previous_rank is not None
        and not previous_leader
    ):
        return "NEW LEADER"

    if (
        current_leader
        and previous_leader
    ):
        return "PERSISTENT LEADER"

    if (
        current_laggard
        and previous_rank is not None
        and not previous_laggard
    ):
        return "NEW LAGGARD"

    if (
        current_laggard
        and previous_laggard
    ):
        return "PERSISTENT LAGGARD"

    if (
        previous_leader
        and not current_leader
    ):
        return "LOSING LEADERSHIP"

    positive_daily = (
        daily_score_change is not None
        and daily_score_change
        >= MINIMUM_MEANINGFUL_SCORE_CHANGE
    )

    positive_weekly = (
        weekly_score_change is not None
        and weekly_score_change
        >= MINIMUM_MEANINGFUL_SCORE_CHANGE
    )

    meaningful_rank_improvement = (
        previous_rank is not None
        and previous_rank - current_rank
        >= MINIMUM_MEANINGFUL_RANK_CHANGE
    )

    if (
        current_score >= 50
        and (
            meaningful_rank_improvement
            or positive_daily
            or positive_weekly
        )
    ):
        return "EMERGING"

    negative_daily = (
        daily_score_change is not None
        and daily_score_change
        <= -MINIMUM_MEANINGFUL_SCORE_CHANGE
    )

    meaningful_rank_decline = (
        previous_rank is not None
        and previous_rank - current_rank
        <= -MINIMUM_MEANINGFUL_RANK_CHANGE
    )

    if (
        negative_daily
        or meaningful_rank_decline
    ):
        return "DETERIORATING"

    return "STABLE"


def determine_sector_cycle(
    *,
    rotation_state: str,
    current_score: int,
    daily_score_change: int | None,
    weekly_score_change: int | None,
    trend: str,
    momentum: str,
) -> str:
    """
    Infer the sector's current analytical cycle.
    """

    if rotation_state in {
        "NEW LEADER",
        "EMERGING",
    }:
        if current_score >= 60:
            return "LEADERSHIP EXPANSION"

        return "EARLY ACCUMULATION"

    if rotation_state == "PERSISTENT LEADER":
        if (
            daily_score_change is not None
            and daily_score_change < 0
        ):
            return "MATURE LEADERSHIP"

        return "LEADERSHIP CONTINUATION"

    if rotation_state == "LOSING LEADERSHIP":
        return "DISTRIBUTION / LEADERSHIP LOSS"

    if rotation_state == "NEW LAGGARD":
        return "BREAKDOWN / DETERIORATION"

    if rotation_state == "PERSISTENT LAGGARD":
        if "IMPROVING" in momentum:
            return "EARLY RECOVERY FROM WEAKNESS"

        return "PERSISTENT WEAKNESS"

    if (
        daily_score_change is not None
        and weekly_score_change is not None
    ):
        if (
            daily_score_change > 0
            and weekly_score_change > 0
        ):
            return "ACCUMULATION"

        if (
            daily_score_change < 0
            and weekly_score_change < 0
        ):
            return "DISTRIBUTION"

        if (
            weekly_score_change < 0
            and daily_score_change > 0
        ):
            return "EARLY RECOVERY"

        if (
            weekly_score_change > 0
            and daily_score_change < 0
        ):
            return "EARLY WEAKENING"

    if "BULLISH" in trend:
        return "POSITIVE CONSOLIDATION"

    if "BEARISH" in trend:
        return "WEAK CONSOLIDATION"

    return "NEUTRAL ROTATION"


def determine_leadership_status(
    *,
    rotation_state: str,
    current_rank: int,
    current_score: int,
) -> str:
    """
    Determine leadership quality.
    """

    if rotation_state == "NEW LEADER":
        return "NEWLY ESTABLISHED LEADERSHIP"

    if rotation_state == "PERSISTENT LEADER":
        return "ESTABLISHED LEADERSHIP"

    if rotation_state == "LOSING LEADERSHIP":
        return "LEADERSHIP UNDER PRESSURE"

    if (
        rotation_state == "EMERGING"
        and current_rank <= LEADING_RANK_LIMIT
    ):
        return "EMERGING LEADERSHIP"

    if current_score >= 55:
        return "CONSTRUCTIVE PARTICIPATION"

    if current_score <= 40:
        return "WEAK PARTICIPATION"

    return "NEUTRAL PARTICIPATION"


def determine_record_rotation_speed(
    *,
    daily_rank_change: int | None,
    daily_score_change: int | None,
) -> str:
    """
    Determine one sector's rotation speed.
    """

    if (
        daily_rank_change is None
        or daily_score_change is None
    ):
        return "INSUFFICIENT HISTORY"

    rank_movement = abs(
        daily_rank_change
    )

    score_movement = abs(
        daily_score_change
    )

    if (
        rank_movement >= 5
        or score_movement >= 12
    ):
        return "VERY FAST"

    if (
        rank_movement >= 3
        or score_movement >= 8
    ):
        return "FAST"

    if (
        rank_movement >= 2
        or score_movement >= 4
    ):
        return "MODERATE"

    return "SLOW"


def determine_record_rotation_risk(
    *,
    rotation_state: str,
    current_risk_level: str,
    daily_rank_change: int | None,
    daily_score_change: int | None,
    weekly_score_change: int | None,
) -> str:
    """
    Determine one sector's rotation risk.
    """

    risk_score = 15

    if current_risk_level == "VERY HIGH":
        risk_score += 35

    elif current_risk_level == "HIGH":
        risk_score += 25

    elif current_risk_level == "MODERATE":
        risk_score += 15

    if rotation_state in {
        "LOSING LEADERSHIP",
        "NEW LAGGARD",
    }:
        risk_score += 25

    if (
        daily_rank_change is not None
        and abs(daily_rank_change) >= 5
    ):
        risk_score += 10

    if (
        daily_score_change is not None
        and weekly_score_change is not None
        and daily_score_change
        * weekly_score_change
        < 0
    ):
        risk_score += 15

    risk_score = clamp_score(
        risk_score
    )

    if risk_score >= 75:
        return "VERY HIGH"

    if risk_score >= 60:
        return "HIGH"

    if risk_score >= 45:
        return "MODERATE"

    if risk_score >= 30:
        return "LOW TO MODERATE"

    return "LOW"


