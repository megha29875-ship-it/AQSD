def determine_rotation_direction(
    records: tuple[SectorRotationRecord, ...],
) -> str:
    """
    Determine overall sector-rotation direction.
    """

    improving = sum(
        record.rotation_state
        in {
            "NEW LEADER",
            "EMERGING",
        }
        or (
            record.daily_score_change is not None
            and record.daily_score_change
            >= MINIMUM_MEANINGFUL_SCORE_CHANGE
        )
        for record in records
    )

    deteriorating = sum(
        record.rotation_state
        in {
            "LOSING LEADERSHIP",
            "NEW LAGGARD",
            "DETERIORATING",
        }
        or (
            record.daily_score_change is not None
            and record.daily_score_change
            <= -MINIMUM_MEANINGFUL_SCORE_CHANGE
        )
        for record in records
    )

    difference = (
        improving
        - deteriorating
    )

    if (
        improving >= 7
        and difference >= 4
    ):
        return "BROAD POSITIVE ROTATION"

    if difference >= 2:
        return "SELECTIVE POSITIVE ROTATION"

    if (
        deteriorating >= 7
        and difference <= -4
    ):
        return "BROAD NEGATIVE ROTATION"

    if difference <= -2:
        return "SELECTIVE NEGATIVE ROTATION"

    return "MIXED ROTATION"


def determine_rotation_breadth(
    *,
    records: tuple[SectorRotationRecord, ...],
    improving_count: int,
    deteriorating_count: int,
) -> str:
    """
    Determine how broad rotation is.
    """

    total = len(
        records
    )

    if total == 0:
        return "UNKNOWN"

    moving = (
        improving_count
        + deteriorating_count
    )

    moving_percentage = (
        moving
        / total
        * 100
    )

    if moving_percentage >= 75:
        return "VERY BROAD"

    if moving_percentage >= 55:
        return "BROAD"

    if moving_percentage >= 35:
        return "MODERATE"

    return "NARROW"


def determine_engine_rotation_speed(
    records: tuple[SectorRotationRecord, ...],
) -> str:
    """
    Determine overall rotation speed.
    """

    available = [
        record
        for record in records
        if record.daily_rank_change is not None
        and record.daily_score_change is not None
    ]

    if not available:
        return "INSUFFICIENT HISTORY"

    average_rank_movement = sum(
        abs(record.daily_rank_change or 0)
        for record in available
    ) / len(available)

    average_score_movement = sum(
        abs(record.daily_score_change or 0)
        for record in available
    ) / len(available)

    if (
        average_rank_movement >= 4
        or average_score_movement >= 10
    ):
        return "VERY FAST"

    if (
        average_rank_movement >= 2.5
        or average_score_movement >= 7
    ):
        return "FAST"

    if (
        average_rank_movement >= 1.5
        or average_score_movement >= 4
    ):
        return "MODERATE"

    return "SLOW"


def determine_leadership_stability(
    *,
    records: tuple[SectorRotationRecord, ...],
) -> str:
    """
    Determine persistence of top-sector leadership.
    """

    current_leaders = [
        record
        for record in records
        if is_current_leader(
            record.current_rank
        )
    ]

    if not current_leaders:
        return "UNKNOWN"

    persistent = sum(
        record.rotation_state
        == "PERSISTENT LEADER"
        for record in current_leaders
    )

    new = sum(
        record.rotation_state
        == "NEW LEADER"
        for record in current_leaders
    )

    if persistent == len(
        current_leaders
    ):
        return "VERY STABLE"

    if persistent >= 2:
        return "STABLE"

    if new >= 2:
        return "LEADERSHIP TRANSITION"

    return "MIXED"


def determine_dominant_sector_cycle(
    records: tuple[SectorRotationRecord, ...],
) -> str:
    """
    Determine the most common sector cycle.
    """

    if not records:
        return "UNKNOWN"

    counts: dict[str, int] = {}

    for record in records:
        counts[record.sector_cycle] = (
            counts.get(
                record.sector_cycle,
                0,
            )
            + 1
        )

    return max(
        counts,
        key=counts.get,
    )


def calculate_rotation_risk(
    *,
    records: tuple[SectorRotationRecord, ...],
    rotation_speed: str,
    leadership_stability: str,
    weekly_history_available: bool,
) -> tuple[int, str]:
    """
    Calculate overall sector-rotation risk.
    """

    risk_score = 20.0

    high_risk_sectors = sum(
        record.rotation_risk
        in {
            "HIGH",
            "VERY HIGH",
        }
        for record in records
    )

    if records:
        high_risk_percentage = (
            high_risk_sectors
            / len(records)
            * 100
        )

        risk_score += min(
            high_risk_percentage * 0.45,
            30,
        )

    if rotation_speed == "VERY FAST":
        risk_score += 25

    elif rotation_speed == "FAST":
        risk_score += 15

    elif rotation_speed == "MODERATE":
        risk_score += 7

    if leadership_stability == "LEADERSHIP TRANSITION":
        risk_score += 18

    elif leadership_stability == "MIXED":
        risk_score += 10

    if not weekly_history_available:
        risk_score += 10

    final_score = clamp_score(
        risk_score
    )

    if final_score >= 80:
        risk_level = "VERY HIGH"

    elif final_score >= 65:
        risk_level = "HIGH"

    elif final_score >= 45:
        risk_level = "MODERATE"

    elif final_score >= 25:
        risk_level = "LOW TO MODERATE"

    else:
        risk_level = "LOW"

    return (
        final_score,
        risk_level,
    )


def calculate_engine_confidence(
    *,
    records: tuple[SectorRotationRecord, ...],
    previous_available: bool,
    weekly_available: bool,
) -> int:
    """
    Calculate overall sector-rotation confidence.
    """

    if not records:
        return 0

    average_sector_confidence = sum(
        record.current_confidence
        for record in records
    ) / len(records)

    score = (
        average_sector_confidence
        * 0.70
    )

    if previous_available:
        score += 18

    else:
        score -= 15

    if weekly_available:
        score += 12

    else:
        score -= 5

    if len(records) >= 10:
        score += 5

    return clamp_score(
        score
    )


