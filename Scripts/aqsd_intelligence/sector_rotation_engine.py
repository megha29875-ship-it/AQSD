def discover_sector_strength_files() -> dict[date, Path]:
    """
    Discover saved sector-strength summary files.
    """

    files: dict[date, Path] = {}

    if not SECTOR_STRENGTH_DIRECTORY.exists():
        return files

    for file_path in SECTOR_STRENGTH_DIRECTORY.glob(
        "sector_strength_summary_*.csv"
    ):
        file_date = extract_date_from_filename(
            file_path
        )

        if file_date is not None:
            files[file_date] = file_path

    return files


def select_analysis_dates(
    *,
    requested_date: date,
    available_dates: list[date],
    weekly_lookback_sessions: int,
) -> tuple[
    date,
    date | None,
    date | None,
]:
    """
    Select current, previous and weekly-reference dates.
    """

    eligible_dates = sorted(
        value
        for value in available_dates
        if value <= requested_date
    )

    if not eligible_dates:
        raise RuntimeError(
            "No sector-strength summary is available on or before "
            f"{requested_date}."
        )

    analysis_date = eligible_dates[-1]

    previous_date = (
        eligible_dates[-2]
        if len(eligible_dates) >= 2
        else None
    )

    weekly_reference_date: date | None = None

    weekly_position = (
        len(eligible_dates)
        - 1
        - weekly_lookback_sessions
    )

    if weekly_position >= 0:
        weekly_reference_date = eligible_dates[
            weekly_position
        ]

    return (
        analysis_date,
        previous_date,
        weekly_reference_date,
    )


