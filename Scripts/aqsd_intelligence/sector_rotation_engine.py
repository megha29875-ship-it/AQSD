def parse_date(
    value: str,
) -> date:
    """
    Parse YYYY-MM-DD.
    """

    try:
        return datetime.strptime(
            value,
            "%Y-%m-%d",
        ).date()

    except ValueError as exc:
        raise ValueError(
            "Invalid date format. Use YYYY-MM-DD."
        ) from exc


def parse_arguments() -> argparse.Namespace:
    """
    Read command-line arguments.
    """

    parser = argparse.ArgumentParser(
        description=(
            "Run the AQSD Sector Rotation Engine."
        )
    )

    parser.add_argument(
        "--date",
        required=True,
        help="Requested analysis date in YYYY-MM-DD format.",
    )

    parser.add_argument(
        "--weekly-sessions",
        type=int,
        default=DEFAULT_WEEKLY_LOOKBACK_SESSIONS,
        help=(
            "Number of saved sessions used for the weekly "
            f"comparison. Default: {DEFAULT_WEEKLY_LOOKBACK_SESSIONS}."
        ),
    )

    parser.add_argument(
        "--no-export",
        action="store_true",
        help="Run without creating CSV and Excel outputs.",
    )

    return parser.parse_args()


def main() -> None:
    """
    Command-line entry point.
    """

    arguments = parse_arguments()

    if arguments.weekly_sessions < 1:
        print()
        print("Status : FAILED")
        print("Reason : --weekly-sessions must be at least 1.")
        raise SystemExit(1)

    try:
        result = run_sector_rotation_engine(
            requested_date=parse_date(
                arguments.date
            ),
            weekly_lookback_sessions=(
                arguments.weekly_sessions
            ),
            export=not arguments.no_export,
        )

    except Exception as exc:
        print()
        print("=" * 116)
        print("AQSD SECTOR ROTATION ENGINE")
        print("=" * 116)
        print("Status : FAILED")
        print(f"Reason : {exc}")
        print("=" * 116)

        raise SystemExit(1) from exc

    display_result(
        result
    )


if __name__ == "__main__":
    main()