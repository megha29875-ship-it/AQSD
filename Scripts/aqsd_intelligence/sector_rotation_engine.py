def determine_engine_expected_behaviour(
    *,
    rotation_direction: str,
    rotation_speed: str,
    leadership_stability: str,
    rotation_risk_level: str,
) -> str:
    """
    Determine expected behaviour from sector rotation.
    """

    if rotation_direction == "BROAD POSITIVE ROTATION":
        return (
            "BROADER SECTOR PARTICIPATION MAY SUPPORT A MORE "
            "CONSTRUCTIVE MARKET ENVIRONMENT"
        )

    if rotation_direction == "SELECTIVE POSITIVE ROTATION":
        return (
            "SELECTIVE SECTOR LEADERSHIP MAY SUPPORT ROTATIONAL "
            "OR STOCK-SPECIFIC STRENGTH"
        )

    if rotation_direction == "BROAD NEGATIVE ROTATION":
        return (
            "WIDESPREAD SECTOR DETERIORATION MAY SUPPORT A MORE "
            "DEFENSIVE OR RISK-OFF MARKET ENVIRONMENT"
        )

    if rotation_direction == "SELECTIVE NEGATIVE ROTATION":
        return (
            "WEAKNESS MAY REMAIN CONCENTRATED IN SELECTED SECTORS "
            "WHILE LEADERSHIP NARROWS"
        )

    if (
        rotation_speed in {
            "FAST",
            "VERY FAST",
        }
        and leadership_stability
        == "LEADERSHIP TRANSITION"
    ):
        return (
            "RAPID LEADERSHIP CHANGE MAY CREATE VOLATILE AND "
            "SHORT-LIVED SECTOR MOVES"
        )

    if rotation_risk_level in {
        "HIGH",
        "VERY HIGH",
    }:
        return (
            "SECTOR ROTATION MAY REMAIN UNSTABLE AND REQUIRE "
            "CONFIRMATION FROM PRICE, BREADTH AND PARTICIPANT DATA"
        )

    return (
        "SECTOR LEADERSHIP REMAINS MIXED AND THE MARKET MAY "
        "CONTINUE TO ROTATE BETWEEN GROUPS"
    )


def determine_master_conclusion(
    *,
    rotation_direction: str,
    rotation_breadth: str,
    rotation_speed: str,
    leadership_stability: str,
    dominant_sector_cycle: str,
    rotation_risk_level: str,
) -> str:
    """
    Build one final sector-rotation conclusion.
    """

    if rotation_direction == "BROAD POSITIVE ROTATION":
        return (
            "SECTOR LEADERSHIP IS BROADENING POSITIVELY. IMPROVING "
            "PARTICIPATION ACROSS MULTIPLE GROUPS SUPPORTS A MORE "
            "CONSTRUCTIVE MARKET-INTERNAL ENVIRONMENT."
        )

    if rotation_direction == "SELECTIVE POSITIVE ROTATION":
        return (
            "SECTOR ROTATION IS POSITIVE BUT SELECTIVE. MARKET "
            "STRENGTH MAY REMAIN CONCENTRATED IN LEADING AND "
            "EMERGING GROUPS."
        )

    if rotation_direction == "BROAD NEGATIVE ROTATION":
        return (
            "SECTOR PARTICIPATION IS DETERIORATING BROADLY. "
            "LEADERSHIP IS WEAKENING AND MARKET-INTERNAL RISK "
            "REMAINS ELEVATED."
        )

    if rotation_direction == "SELECTIVE NEGATIVE ROTATION":
        return (
            "SECTOR WEAKNESS IS EXPANDING SELECTIVELY. LEADERSHIP "
            "MAY NARROW FURTHER UNLESS EMERGING GROUPS STRENGTHEN."
        )

    return (
        f"SECTOR ROTATION IS MIXED. ROTATION BREADTH IS "
        f"{rotation_breadth}, ROTATION SPEED IS {rotation_speed}, "
        f"LEADERSHIP STABILITY IS {leadership_stability}, AND THE "
        f"DOMINANT CYCLE IS {dominant_sector_cycle}. ROTATION RISK "
        f"IS {rotation_risk_level}."
    )


def build_engine_warnings(
    *,
    previous_date: date | None,
    weekly_reference_date: date | None,
    rotation_speed: str,
    leadership_stability: str,
    rotation_risk_level: str,
) -> tuple[str, ...]:
    """
    Build engine-level warnings.
    """

    warnings: list[str] = []

    if previous_date is None:
        warnings.append(
            "Daily sector-rank comparison is unavailable."
        )

    if weekly_reference_date is None:
        warnings.append(
            "Weekly sector-rank comparison requires at least six "
            "saved sector-strength sessions."
        )

    if rotation_speed in {
        "FAST",
        "VERY FAST",
    }:
        warnings.append(
            "Sector leadership is changing rapidly."
        )

    if leadership_stability == "LEADERSHIP TRANSITION":
        warnings.append(
            "The leading-sector group is undergoing a transition."
        )

    if rotation_risk_level in {
        "HIGH",
        "VERY HIGH",
    }:
        warnings.append(
            f"Overall sector-rotation risk is "
            f"{rotation_risk_level.lower()}."
        )

    if not warnings:
        warnings.append(
            "No major sector-rotation warning is active."
        )

    return tuple(
        dict.fromkeys(warnings)
    )


