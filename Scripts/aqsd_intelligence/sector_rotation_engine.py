def normalize_report_columns(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """
    Normalize sector-strength report headings.
    """

    result = dataframe.copy()

    result.columns = [
        re.sub(
            r"_+",
            "_",
            re.sub(
                r"[^A-Za-z0-9]+",
                "_",
                str(column).strip(),
            ),
        ).strip("_")
        for column in result.columns
    ]

    aliases = {
        "RANK": "Rank",
        "SECTOR": "Sector",
        "BREADTH_SCORE": "Breadth_Score",
        "SCORE": "Breadth_Score",
        "STRENGTH": "Strength",
        "TREND": "Trend",
        "MOMENTUM": "Momentum",
        "ROTATION": "Rotation",
        "LEADERSHIP": "Leadership",
        "RISK_LEVEL": "Risk_Level",
        "CONFIDENCE": "Confidence",
    }

    rename_map: dict[str, str] = {}

    for column in result.columns:
        key = str(column).upper()

        if key in aliases:
            rename_map[column] = aliases[key]

    return result.rename(
        columns=rename_map
    )


def read_sector_strength_report(
    file_path: Path,
) -> pd.DataFrame:
    """
    Read one saved sector-strength CSV.
    """

    dataframe = pd.read_csv(
        file_path,
        low_memory=False,
    )

    if dataframe.empty:
        raise RuntimeError(
            f"Sector-strength file is empty: {file_path}"
        )

    dataframe = normalize_report_columns(
        dataframe
    )

    required_columns = {
        "Rank",
        "Sector",
        "Breadth_Score",
    }

    missing_columns = (
        required_columns
        - set(dataframe.columns)
    )

    if missing_columns:
        raise KeyError(
            "Sector-strength report is missing columns: "
            + ", ".join(
                sorted(missing_columns)
            )
        )

    optional_defaults: dict[str, object] = {
        "Strength": "UNKNOWN",
        "Trend": "UNKNOWN",
        "Momentum": "UNKNOWN",
        "Rotation": "UNKNOWN",
        "Leadership": "UNKNOWN",
        "Risk_Level": "UNKNOWN",
        "Confidence": 0,
    }

    for column, default in optional_defaults.items():
        if column not in dataframe.columns:
            dataframe[column] = default

    dataframe["Sector"] = (
        dataframe["Sector"]
        .fillna("UNKNOWN")
        .astype(str)
        .str.strip()
        .str.upper()
    )

    dataframe["Rank"] = pd.to_numeric(
        dataframe["Rank"],
        errors="coerce",
    )

    dataframe["Breadth_Score"] = pd.to_numeric(
        dataframe["Breadth_Score"],
        errors="coerce",
    )

    dataframe["Confidence"] = pd.to_numeric(
        dataframe["Confidence"],
        errors="coerce",
    ).fillna(0)

    for column in (
        "Strength",
        "Trend",
        "Momentum",
        "Rotation",
        "Leadership",
        "Risk_Level",
    ):
        dataframe[column] = (
            dataframe[column]
            .fillna("UNKNOWN")
            .astype(str)
            .str.strip()
            .str.upper()
        )

    dataframe = dataframe.dropna(
        subset=[
            "Rank",
            "Breadth_Score",
        ]
    )

    dataframe = dataframe.loc[
        dataframe["Sector"].ne("UNKNOWN")
    ].copy()

    dataframe["Rank"] = (
        dataframe["Rank"]
        .round()
        .astype(int)
    )

    dataframe["Breadth_Score"] = (
        dataframe["Breadth_Score"]
        .round()
        .astype(int)
    )

    dataframe["Confidence"] = (
        dataframe["Confidence"]
        .round()
        .astype(int)
    )

    dataframe = dataframe.drop_duplicates(
        subset=["Sector"],
        keep="last",
    )

    return dataframe.sort_values(
        "Rank"
    ).reset_index(
        drop=True
    )


def build_sector_map(
    dataframe: pd.DataFrame | None,
) -> dict[str, pd.Series]:
    """
    Convert a sector report to a sector-indexed map.
    """

    if dataframe is None:
        return {}

    return {
        str(row["Sector"]): row
        for _, row
        in dataframe.iterrows()
    }


