def run_sector_rotation_engine(
    *,
    requested_date: date,
    weekly_lookback_sessions: int = (
        DEFAULT_WEEKLY_LOOKBACK_SESSIONS
    ),
    export: bool = True,
) -> SectorRotationEngineResult:
    """
    Run the complete Sector Rotation Engine.
    """

    strength_files = (
        discover_sector_strength_files()
    )

    if not strength_files:
        raise FileNotFoundError(
            "No sector-strength summary files were found in: "
            f"{SECTOR_STRENGTH_DIRECTORY}"
        )

    (
        analysis_date,
        previous_date,
        weekly_reference_date,
    ) = select_analysis_dates(
        requested_date=requested_date,
        available_dates=list(
            strength_files.keys()
        ),
        weekly_lookback_sessions=(
            weekly_lookback_sessions
        ),
    )

    current_dataframe = (
        read_sector_strength_report(
            strength_files[analysis_date]
        )
    )

    previous_dataframe = (
        read_sector_strength_report(
            strength_files[previous_date]
        )
        if previous_date is not None
        else None
    )

    weekly_dataframe = (
        read_sector_strength_report(
            strength_files[
                weekly_reference_date
            ]
        )
        if weekly_reference_date is not None
        else None
    )

    records = build_rotation_records(
        current=current_dataframe,
        previous=previous_dataframe,
        weekly=weekly_dataframe,
    )

    if not records:
        raise RuntimeError(
            "No sector-rotation records were created."
        )

    new_leaders = tuple(
        record
        for record in records
        if record.rotation_state
        == "NEW LEADER"
    )

    persistent_leaders = tuple(
        record
        for record in records
        if record.rotation_state
        == "PERSISTENT LEADER"
    )

    emerging_sectors = tuple(
        record
        for record in records
        if record.rotation_state
        == "EMERGING"
    )

    losing_leadership = tuple(
        record
        for record in records
        if record.rotation_state
        == "LOSING LEADERSHIP"
    )

    new_laggards = tuple(
        record
        for record in records
        if record.rotation_state
        == "NEW LAGGARD"
    )

    persistent_laggards = tuple(
        record
        for record in records
        if record.rotation_state
        == "PERSISTENT LAGGARD"
    )

    stable_sectors = tuple(
        record
        for record in records
        if record.rotation_state
        == "STABLE"
    )

    improving_sectors = sum(
        (
            record.rotation_state
            in {
                "NEW LEADER",
                "EMERGING",
            }
            or (
                record.daily_score_change
                is not None
                and record.daily_score_change
                >= MINIMUM_MEANINGFUL_SCORE_CHANGE
            )
        )
        for record in records
    )

    deteriorating_sectors = sum(
        (
            record.rotation_state
            in {
                "LOSING LEADERSHIP",
                "NEW LAGGARD",
                "DETERIORATING",
            }
            or (
                record.daily_score_change
                is not None
                and record.daily_score_change
                <= -MINIMUM_MEANINGFUL_SCORE_CHANGE
            )
        )
        for record in records
    )

    stable_sector_count = (
        len(records)
        - improving_sectors
        - deteriorating_sectors
    )

    if stable_sector_count < 0:
        stable_sector_count = 0

    rotation_direction = (
        determine_rotation_direction(
            records
        )
    )

    rotation_breadth = determine_rotation_breadth(
        records=records,
        improving_count=improving_sectors,
        deteriorating_count=(
            deteriorating_sectors
        ),
    )

    rotation_speed = (
        determine_engine_rotation_speed(
            records
        )
    )

    leadership_stability = (
        determine_leadership_stability(
            records=records
        )
    )

    dominant_sector_cycle = (
        determine_dominant_sector_cycle(
            records
        )
    )

    (
        rotation_risk_score,
        rotation_risk_level,
    ) = calculate_rotation_risk(
        records=records,
        rotation_speed=rotation_speed,
        leadership_stability=(
            leadership_stability
        ),
        weekly_history_available=(
            weekly_reference_date
            is not None
        ),
    )

    confidence = calculate_engine_confidence(
        records=records,
        previous_available=(
            previous_date is not None
        ),
        weekly_available=(
            weekly_reference_date
            is not None
        ),
    )

    expected_behaviour = (
        determine_engine_expected_behaviour(
            rotation_direction=(
                rotation_direction
            ),
            rotation_speed=rotation_speed,
            leadership_stability=(
                leadership_stability
            ),
            rotation_risk_level=(
                rotation_risk_level
            ),
        )
    )

    master_conclusion = (
        determine_master_conclusion(
            rotation_direction=(
                rotation_direction
            ),
            rotation_breadth=(
                rotation_breadth
            ),
            rotation_speed=rotation_speed,
            leadership_stability=(
                leadership_stability
            ),
            dominant_sector_cycle=(
                dominant_sector_cycle
            ),
            rotation_risk_level=(
                rotation_risk_level
            ),
        )
    )

    concise_summary = (
        f"{rotation_direction} | "
        f"{rotation_breadth} BREADTH | "
        f"{rotation_speed} SPEED | "
        f"{leadership_stability} LEADERSHIP | "
        f"{dominant_sector_cycle} | "
        f"{rotation_risk_level} RISK | "
        f"{confidence}% CONFIDENCE"
    )

    explanation = (
        f"The Sector Rotation Engine analysed {len(records)} sectors. "
        f"{improving_sectors} sectors are improving, "
        f"{deteriorating_sectors} are deteriorating and "
        f"{stable_sector_count} are stable. "
        f"There are {len(new_leaders)} new leaders, "
        f"{len(persistent_leaders)} persistent leaders, "
        f"{len(emerging_sectors)} emerging sectors and "
        f"{len(losing_leadership)} sectors losing leadership. "
        f"Overall rotation is classified as "
        f"{rotation_direction.lower()}, with "
        f"{rotation_breadth.lower()} breadth and "
        f"{rotation_speed.lower()} speed. "
        f"Leadership stability is "
        f"{leadership_stability.lower()}, the dominant sector cycle "
        f"is {dominant_sector_cycle.lower()}, and rotation risk is "
        f"{rotation_risk_level.lower()} at "
        f"{rotation_risk_score}%. Confidence is {confidence}%."
    )

    warnings = build_engine_warnings(
        previous_date=previous_date,
        weekly_reference_date=(
            weekly_reference_date
        ),
        rotation_speed=rotation_speed,
        leadership_stability=(
            leadership_stability
        ),
        rotation_risk_level=(
            rotation_risk_level
        ),
    )

    if previous_date is None:
        overall_status = (
            "INSUFFICIENT HISTORY"
        )

    else:
        overall_status = "SUCCESS"

    result = SectorRotationEngineResult(
        requested_date=requested_date,
        analysis_date=analysis_date,
        previous_date=previous_date,
        weekly_reference_date=(
            weekly_reference_date
        ),

        sectors_analysed=len(records),

        new_leaders=new_leaders,
        persistent_leaders=(
            persistent_leaders
        ),
        emerging_sectors=emerging_sectors,
        losing_leadership=(
            losing_leadership
        ),
        new_laggards=new_laggards,
        persistent_laggards=(
            persistent_laggards
        ),
        stable_sectors=stable_sectors,

        improving_sectors=(
            improving_sectors
        ),
        deteriorating_sectors=(
            deteriorating_sectors
        ),
        stable_sector_count=(
            stable_sector_count
        ),

        rotation_direction=(
            rotation_direction
        ),
        rotation_breadth=rotation_breadth,
        rotation_speed=rotation_speed,
        leadership_stability=(
            leadership_stability
        ),
        dominant_sector_cycle=(
            dominant_sector_cycle
        ),

        rotation_risk_score=(
            rotation_risk_score
        ),
        rotation_risk_level=(
            rotation_risk_level
        ),

        confidence=confidence,
        expected_behaviour=(
            expected_behaviour
        ),
        master_conclusion=(
            master_conclusion
        ),
        concise_summary=concise_summary,
        explanation=explanation,

        records=records,
        warnings=warnings,

        csv_file=None,
        excel_file=None,

        status=overall_status,
    )

    if export:
        csv_file, excel_file = export_result(
            result
        )

        result = SectorRotationEngineResult(
            requested_date=(
                result.requested_date
            ),
            analysis_date=(
                result.analysis_date
            ),
            previous_date=(
                result.previous_date
            ),
            weekly_reference_date=(
                result.weekly_reference_date
            ),

            sectors_analysed=(
                result.sectors_analysed
            ),

            new_leaders=result.new_leaders,
            persistent_leaders=(
                result.persistent_leaders
            ),
            emerging_sectors=(
                result.emerging_sectors
            ),
            losing_leadership=(
                result.losing_leadership
            ),
            new_laggards=(
                result.new_laggards
            ),
            persistent_laggards=(
                result.persistent_laggards
            ),
            stable_sectors=(
                result.stable_sectors
            ),

            improving_sectors=(
                result.improving_sectors
            ),
            deteriorating_sectors=(
                result.deteriorating_sectors
            ),
            stable_sector_count=(
                result.stable_sector_count
            ),

            rotation_direction=(
                result.rotation_direction
            ),
            rotation_breadth=(
                result.rotation_breadth
            ),
            rotation_speed=(
                result.rotation_speed
            ),
            leadership_stability=(
                result.leadership_stability
            ),
            dominant_sector_cycle=(
                result.dominant_sector_cycle
            ),

            rotation_risk_score=(
                result.rotation_risk_score
            ),
            rotation_risk_level=(
                result.rotation_risk_level
            ),

            confidence=result.confidence,
            expected_behaviour=(
                result.expected_behaviour
            ),
            master_conclusion=(
                result.master_conclusion
            ),
            concise_summary=(
                result.concise_summary
            ),
            explanation=result.explanation,

            records=result.records,
            warnings=result.warnings,

            csv_file=csv_file,
            excel_file=excel_file,

            status=result.status,
        )

    return result


