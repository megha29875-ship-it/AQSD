def calculate_rank_change(
    *,
    current_rank: int,
    previous_rank: int | None,
) -> int | None:
    """
    Calculate rank improvement.

    Positive value means the sector moved higher in rank.

    Example
    -------
    Previous rank 8, current rank 3:

        8 - 3 = +5
    """

    if previous_rank is None:
        return None

    return previous_rank - current_rank


def calculate_score_change(
    *,
    current_score: int,
    previous_score: int | None,
) -> int | None:
    """
    Calculate sector-score change.
    """

    if previous_score is None:
        return None

    return current_score - previous_score


def is_current_leader(
    rank: int,
) -> bool:
    """
    Return True for a top-three sector.
    """

    return rank <= LEADER_RANK_LIMIT


def is_current_leading_group(
    rank: int,
) -> bool:
    """
    Return True for a top-five sector.
    """

    return rank <= LEADING_RANK_LIMIT


def is_laggard(
    *,
    rank: int,
    total_sectors: int,
) -> bool:
    """
    Return True for a bottom-ranked sector.
    """

    threshold = max(
        1,
        total_sectors
        - LAGGARD_RANK_COUNT
        + 1,
    )

    return rank >= threshold


