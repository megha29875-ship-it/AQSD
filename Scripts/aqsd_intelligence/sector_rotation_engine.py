def clamp_score(
    value: float,
) -> int:
    """
    Restrict a value to the range 0-100.
    """

    return max(
        0,
        min(
            round(value),
            100,
        ),
    )


def safe_int(
    value: object,
    default: int = 0,
) -> int:
    """
    Convert a value to integer safely.
    """

    try:
        if pd.isna(value):
            return default
    except TypeError:
        pass

    try:
        return int(
            round(
                float(value)
            )
        )

    except (
        TypeError,
        ValueError,
    ):
        return default


def normalize_text(
    value: object,
    default: str = "UNKNOWN",
) -> str:
    """
    Normalize a text value.
    """

    if value is None:
        return default

    try:
        if pd.isna(value):
            return default
    except TypeError:
        pass

    text = str(value).strip().upper()

    return text or default


def format_optional_change(
    value: int | None,
) -> str:
    """
    Format an optional signed integer.
    """

    if value is None:
        return "NOT AVAILABLE"

    return f"{value:+d}"


def extract_date_from_filename(
    file_path: Path,
) -> date | None:
    """
    Extract YYYYMMDD from a sector-strength filename.
    """

    match = re.search(
        r"(\d{8})",
        file_path.stem,
    )

    if match is None:
        return None

    try:
        return datetime.strptime(
            match.group(1),
            "%Y%m%d",
        ).date()

    except ValueError:
        return None


