    """
    Build all sector-rotation records.
    """

    previous_map = build_sector_map(
        previous
    )

    weekly_map = build_sector_map(
        weekly
    )

    total_sectors = len(
        current
    )

    records: list[
        SectorRotationRecord
    ] = []

    for _, current_row in current.iterrows():
        sector = str(
            current_row["Sector"]
        )

        previous_row = previous_map.get(
            sector
        )

        weekly_row = weekly_map.get(
            sector
        )

        current_rank = safe_int(
            current_row["Rank"]
        )

        previous_rank = (
            safe_int(
                previous_row["Rank"]
            )
            if previous_row is not None
            else None
        )

        weekly_rank = (
            safe_int(
                weekly_row["Rank"]
            )
            if weekly_row is not None
            else None
        )

        current_score = safe_int(
            current_row["Breadth_Score"]
        )

        previous_score = (
            safe_int(
                previous_row["Breadth_Score"]
            )
            if previous_row is not None
            else None
        )

        weekly_score = (
            safe_int(
                weekly_row["Breadth_Score"]
            )
            if weekly_row is not None
            else None
        )

        daily_rank_change = calculate_rank_change(
            current_rank=current_rank,
            previous_rank=previous_rank,
        )

        weekly_rank_change = calculate_rank_change(
            current_rank=current_rank,
            previous_rank=weekly_rank,
        )

        daily_score_change = calculate_score_change(
            current_score=current_score,
            previous_score=previous_score,
        )

        weekly_score_change = calculate_score_change(
            current_score=current_score,
            previous_score=weekly_score,
        )

        current_strength = normalize_text(
            current_row["Strength"]
        )

        current_trend = normalize_text(
            current_row["Trend"]
        )

        current_momentum = normalize_text(
            current_row["Momentum"]
        )

